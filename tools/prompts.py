def plate(text, kind):
    """A plate's texels: the text centred, white on clear for the header,
    black on white for a plate."""
    cov = lettering('gothic', text, PLATE_W + 60, PLATE_H, 4.0, PLATE_BASE, PLATE_SIZE, PLATE_WIDE)
