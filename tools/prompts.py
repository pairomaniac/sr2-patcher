RECORD_TXR, RECORD_SHEET = 'Record.txr', 13
RECORD_PAD = (('LB BUTTON', 64), ('RB BUTTON', 84))     # the lines and their baselines, as rows of the sheet: the stock's 34 rows down, where it has a second arrow
RECORD_CAPS = 9                           # the caps' height, whole, so their tops and feet are sharp as the stock's are
RECORD_CAP_RATIO = 1409 / 2048.0          # the face's cap height to its size
RECORD_WIDE, RECORD_BOLD, RECORD_TRACK, RECORD_SPACE = 0.9, 0.125, 0.0, 0.15625
RECORD_X = 33.5                           # the first letter's origin, a column of the sheet: its stem a full texel then half, on the stock P's
RECORD_AT = (31, 53, 81, 33)              # the L LEVER and R LEVER lettering, which no entry draws: x, y, width, height
RECORD_WHITE = 0x0fff                     # the sheet's lettering is white, its alpha the shape


def record_line(text, base, x0, y0, width, height):
    """A line's coverage over a rectangle of the sheet."""
    return lettering('narrow', text, width, height, RECORD_X - x0, base - y0, RECORD_CAPS / RECORD_CAP_RATIO, RECORD_WIDE, RECORD_BOLD, RECORD_TRACK, RECORD_SPACE)


def record(_game, log):
    x0, y0, w, h = RECORD_AT
    area = [[0.0] * w for _ in range(h)]
    for text, base in RECORD_PAD:
        for y, row in enumerate(record_line(text, base, x0, y0, w, h)):
            for x, c in enumerate(row):
                area[y][x] = max(area[y][x], c)
    if any(area[0]) or any(area[-1]) or any(row[0] or row[-1] for row in area):
        raise SystemExit('the Records lettering reaches the edge of its rectangle')
    log('records: %s and %s at (%d, %d), %d by %d' % (RECORD_PAD[0][0], RECORD_PAD[1][0], x0, y0, w, h))
    return [(RECORD_TXR, RECORD_SHEET, x0, y0, w, h, '', [int(round(c * 15)) << 12 | RECORD_WHITE for row in area for c in row])]


# ---- the Device Settings page's hint bar ------------------------------

# The page's two lines, in the face the frame's own messages are in
# (OPTIONS.TXR sheet 4, a narrow bold grotesque with 11 px caps), dark
# on white. Each is cut in two at the word gap nearest its middle,
# because a line is wider than the sheet, and each half is a strip with
# a margin of white each side, so its edges filter to white. They go on
# the sheet the patcher appends to OPTIONS.TXR.
HINT_TXR, HINT_STOCK = 'OPTIONS.TXR', 4
HINT_KEYS = ('Hit the ESC key to go back to the', 58, 46)     # a stock line's first words, the row its strip starts on and a column left of it
HINT_LINES = ('Select an action and hit the key to bind it', 'Hit the button to bind it, or hit ESC to keep it')
HINT_SHEET = 12                           # the appended sheet
HINT_TOPS = (130, 150, 170, 190)          # the strips' rows on it, from column 1
HINT_ROWS, HINT_MARGIN = 17, 2            # a strip starts a row above the ascenders, as the stock's do
HINT_CAPS = 11
HINT_WIDE, HINT_BOLD, HINT_TRACK = 0.9, 0.5, 0.75
HINT_X, HINT_BASE = 3.3125, 12.625        # the first letter's origin past the column, and the baseline, in a strip
HINT_GAP = 3                              # clear columns that make a word gap


def hint_line(text, width):
    return lettering('narrow', text, width, HINT_ROWS, HINT_X, HINT_BASE, HINT_CAPS / RECORD_CAP_RATIO, HINT_WIDE, HINT_BOLD, HINT_TRACK)


def halves(cov):
    """A line's coverage cut in two at the word gap nearest its middle:
    (first column, cut column, column after the last) of the ink."""
    rows, width = len(cov), len(cov[0])
    inked = [any(int(round(cov[y][x] * 15)) for y in range(rows)) for x in range(width)]
    first, last = inked.index(True), width - 1 - inked[::-1].index(True)
    gaps, x = [], first
    while x <= last:                        # the word gaps: runs of clear columns
        if not inked[x]:
            end = x
            while not inked[end]:
                end += 1
            if end - x >= HINT_GAP:
                gaps.append((x + end) // 2)
            x = end
        x += 1
    if not gaps:
        raise SystemExit('no word gap to cut a line at')
    return first, min(gaps, key=lambda g: abs(g - (first + last) / 2.0)), last + 1


def strip(cov, a, b, ink=0xf000, paper=0xffff):
    """A strip of 4444 texels from columns a to b of a line's coverage,
    with HINT_MARGIN texels of paper each side: the ink's colour by the
    coverage, over the paper's."""
    out = []
    for row in cov:
        values = [0.0] * HINT_MARGIN + row[a:b] + [0.0] * HINT_MARGIN
        for c in values:
            level = int(round(c * 15))
            out.append(paper if not level else (ink if level == 15 else
                       0xf000 | sum(int(round((paper >> s & 15) * (15 - level) / 15.0 + (ink >> s & 15) * level / 15.0)) << s for s in (8, 4, 0))))
    return out


def line_strips(cov, file, sheet_, tops, variant='', ink=0xf000, paper=0xffff):
    """A line's two halves as blits at the given rows of a sheet."""
    first, cut, end = halves(cov)
    blits = []
    for (a, b), top in zip(((first, cut), (cut, end)), tops):
        w = b - a + 2 * HINT_MARGIN
        if 1 + w > 255:
            raise SystemExit('half of a line is %d texels wide, too wide for the sheet' % w)
        blits.append((file, sheet_, 1, top, w, len(cov), variant, strip(cov, a, b, ink, paper)))
    return blits


