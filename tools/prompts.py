JAPANESE_WEIGHT = 700
_fonts = {}


def face(name, size):
    """A face at a size, from one of its known paths, else wherever
    fontconfig says it is."""
    from PIL import ImageFont
    if (name, size) not in _fonts:
        match, files, paths, missing = FACES[name]
        paths = list(paths)
        try:
            found = subprocess.run(['fc-match', '-f', '%{file}', match], capture_output=True, text=True, timeout=10).stdout.strip()
            if os.path.basename(found) in files:
                paths.append(found)
        except (OSError, subprocess.SubprocessError):
            pass
        path = next((p for p in paths if os.path.isfile(p)), None)
        if path is None:
            raise SystemExit(missing)
        fnt = ImageFont.truetype(path, size)
        if name == 'japanese':
            try:
                axes = fnt.get_variation_axes()
                fnt.set_variation_by_axes([JAPANESE_WEIGHT if a['name'] in (b'Weight', 'Weight') else a['default'] for a in axes])
            except OSError:
                pass                    # a static Bold file
        _fonts[name, size] = fnt
    return _fonts[name, size]


def lettering(name, text, width, height, x, base, size, wide=1.0, bold=0.0, track=0.0, space=0.0):
    """A line's coverage, 0..1, a row a list: the face at a size in
    pixels, its first letter's origin at x and its baseline at base, set
    wide times as wide, bold pixels bolder across, the letters track
    pixels apart and the spaces space wider. Drawn SAMPLES times the size
    and averaged down."""
    return averaged(drawn(name, text, width, height, x, base, size, wide, bold, track, space), width, height)


def averaged(big, width, height):
    """A drawn line's coverage, 0..1, a row a list."""
    from PIL import Image
    flat = big.crop((0, 0, width * SAMPLES, height * SAMPLES)).resize((width, height), Image.BOX).tobytes()
    return [[flat[y * width + col] / 255.0 for col in range(width)] for y in range(height)]


def drawn(name, text, width, height, x, base, size, wide=1.0, bold=0.0, track=0.0, space=0.0):
    """A line as lettering() draws it, SAMPLES times the size, an L image."""
    from PIL import Image, ImageChops, ImageDraw
    fnt = face(name, size * SAMPLES)
    big_w = int(width * SAMPLES / wide) + 4 * SAMPLES
    big = Image.new('L', (big_w, height * SAMPLES), 0)
    draw = ImageDraw.Draw(big)
    at = x * SAMPLES / wide
    for ch in text:
        draw.text((at, base * SAMPLES), ch, font=fnt, fill=255, anchor='ls')
        at += fnt.getlength(ch) + (track + (space if ch == ' ' else 0)) * SAMPLES / wide
    spread_by = int(round(bold * SAMPLES / wide))
    out = big.copy()
    if spread_by:
        for dx in range(-(spread_by // 2), spread_by - spread_by // 2 + 1):
            moved = Image.new('L', big.size, 0)
            moved.paste(big, (-dx, 0))
            out = ImageChops.lighter(out, moved)
    if wide != 1.0:
        out = out.resize((int(round(big_w * wide)), height * SAMPLES), Image.LANCZOS)
    return out


def title_coverage(text, width):
    return lettering('times', text, width, TITLE_ROWS, TITLE_X, TITLE_BASE, TITLE_SIZE, TITLE_WIDE, TITLE_BOLD, TITLE_TRACK)


def spread(cov, r2):
    """Each texel the most of those within sqrt(r2) of it."""
    h, w = len(cov), len(cov[0])
    reach = int(math.sqrt(r2))
    offsets = [(dy, dx) for dy in range(-reach, reach + 1) for dx in range(-reach, reach + 1) if dy * dy + dx * dx <= r2]
    out = [[0.0] * w for _ in range(h)]
    for y in range(h):
        for dy, dx in offsets:
            if not 0 <= y + dy < h:
                continue
            src, dst = cov[y + dy], out[y]
            for x in range(max(0, -dx), min(w, w - dx)):
                if src[x + dx] > dst[x]:
                    dst[x] = src[x + dx]
    return out


def blurred(a, sigma):
    """A Gaussian blur, nothing beyond the edges."""
    h, w = len(a), len(a[0])
    reach = int(math.ceil(sigma * 4))
    kernel = [math.exp(-0.5 * (i / sigma) ** 2) for i in range(-reach, reach + 1)]
    total = sum(kernel)
    kernel = [k / total for k in kernel]
    cols = [[sum(kernel[i + reach] * a[y + i][x] for i in range(-reach, reach + 1) if 0 <= y + i < h) for x in range(w)] for y in range(h)]
    return [[sum(kernel[i + reach] * row[x + i] for i in range(-reach, reach + 1) if 0 <= x + i < w) for x in range(w)] for row in cols]


def title_image(text, width):
    """The prompt as 4444 texels, a row a list: the gradient through the
    lettering, over the glow."""
    cov = title_coverage(text, width)
    glow = blurred(spread(cov, TITLE_SPREAD), TITLE_SIGMA)
    out = []
    for y in range(TITLE_ROWS):
        i = min(max(y - TITLE_CAPS, 0), len(TITLE_GREEN) - 1)
        fill = (15, TITLE_GREEN[i], TITLE_BLUE[i])
        row = []
        for x in range(width):
            c = cov[y][x]
            alpha = c + (1 - c) * min(1.0, glow[y][x] * TITLE_GAIN)
            a = int(round(alpha * 15))
            if not a:
                row.append(0)
                continue
            r, g, b = (int(round(min(15.0, c * v / alpha))) for v in fill)
            row.append(a << 12 | r << 8 | g << 4 | b)
        out.append(row)
    return out, cov


def title_stock(texels):
    """The stock prompt, whole, from its two strips in the sheet."""
    (row0, col0), (row1, col1) = TITLE_STRIPS
    out = []
    for r in range(TITLE_ROWS):
        a, b = texels[(row0 + r) * 256:(row0 + r + 1) * 256], texels[(row1 + r) * 256:(row1 + r + 1) * 256]
        if a[col1:] != b[:256 - col1]:
            raise SystemExit('TITLE.TXR: the prompt\'s two strips do not overlap as expected')
        out.append(a + b[256 - col1:])
    return out


def levels(a, b):
    """How far apart two 4444 texels are, the most over their channels."""
    return max(abs((a >> s & 15) - (b >> s & 15)) for s in (12, 8, 4, 0))


def title(game, log):
    if game:
        fmt, width, texels = sheet(game, TITLE_TXR, TITLE_SHEET)
        if (fmt, width, len(texels)) != (8, 256, 256 * 256):
            raise SystemExit('TITLE.TXR sheet %d is not a 256x256 4444' % TITLE_SHEET)
        stock = title_stock(texels)
        keys, _cov = title_image(TITLE_KEYS, len(stock[0]))
        apart = [levels(s, k) for srow, krow in zip(stock, keys) for s, k in zip(srow, krow) if s >> 12 or k >> 12]
        log('title: the model of %s against the stock: %d of %d texels differ, %d by more than one level of 15, %d by more than two'
            % (TITLE_KEYS, sum(d > 0 for d in apart), len(apart), sum(d > 1 for d in apart), sum(d > 2 for d in apart)))
    wide = 480
    pad, cov = title_image(TITLE_PAD, wide)
    ink = [x for x in range(wide) if any(cov[y][x] >= 0.02 for y in range(TITLE_ROWS))]
    lit = [x for x in range(wide) if any(pad[y][x] >> 12 for y in range(TITLE_ROWS))]
    margin = max(ink[0] - lit[0], lit[-1] - ink[-1]) + 2
    left, right = ink[0] - margin, ink[-1] + 1 + margin
    right += (right - left) & 1
    rows = [y for y in range(TITLE_ROWS) if any(t >> 12 for t in pad[y])]
    if rows[0] < TITLE_BAND[0] or rows[-1] >= TITLE_BAND[1]:
        raise SystemExit('the title\'s glow reaches rows %d to %d, past the band' % (rows[0], rows[-1]))
    half = (right - left) // 2
    if half > 250:
        raise SystemExit('the title is %d texels wide, too wide for two strips' % (right - left))
    log('title: %s, %d wide in two strips of %d' % (TITLE_PAD, right - left, half))
    blits = []
    for (x, y), first in zip(TITLE_AT, (left, left + half)):
        strip = [t for row in pad[TITLE_BAND[0]:TITLE_BAND[1]] for t in row[first:first + half]]
        blits.append((TITLE_TXR, TITLE_SHEET, x, y, half, TITLE_BAND[1] - TITLE_BAND[0], '', strip))
    return blits


def share(model, stock):
    """How far a model's coverage is from the stock's: the squared
    difference as a share of the stock's ink."""
    return sum((m - s) ** 2 for mrow, srow in zip(model, stock) for m, s in zip(mrow, srow)) / sum(s for row in stock for s in row)


# ---- the attract screen ----------------------------------------------

ATTRACT_TXR, ATTRACT_SHEET = 'ADV_TXT.TXR', 0
ATTRACT_KEYS, ATTRACT_PAD = 'PRESS ENTER KEY', 'PRESS START BUTTON'
ATTRACT_SIZE, ATTRACT_WIDE, ATTRACT_TRACK, ATTRACT_SPACE = 21.0, 1.25, -1.5, 0.25
ATTRACT_X, ATTRACT_BASE = 29.9375, 17.125      # the first letter's origin and the baseline, in the stock image
ATTRACT_ROWS = 19                         # the stock image: rows 217 to 235 of its sheet, every column
ATTRACT_TOP = 217
ATTRACT_INK = 10                          # of 31: fainter coverage than this is outline, not lettering
ATTRACT_OUTLINE = 0x8842                  # the outline's texel, 1555: every texel beside the lettering, corners too
ATTRACT_ON = 3                            # the sheet the pad's prompt goes on: rows 172 to 255 are free
ATTRACT_AT = (2, 176)


def attract_image(text, width):
    """The prompt as 1555 texels, a row a list, and its coverage: white
    lettering, greys at its edges, the outline round it."""
    cov = lettering('italic', text, width, ATTRACT_ROWS, ATTRACT_X, ATTRACT_BASE, ATTRACT_SIZE, ATTRACT_WIDE, 0.0, ATTRACT_TRACK, ATTRACT_SPACE)
    grey = [[int(round(c * 31)) for c in row] for row in cov]
    out = []
    for y in range(ATTRACT_ROWS):
        row = []
        for x in range(width):
            g = grey[y][x]
            if g >= ATTRACT_INK:
                row.append(0x8000 | g << 10 | g << 5 | g)
            elif any(grey[yy][xx] >= ATTRACT_INK for yy in range(max(0, y - 1), min(ATTRACT_ROWS, y + 2)) for xx in range(max(0, x - 1), min(width, x + 2))):
                row.append(ATTRACT_OUTLINE)
            else:
                row.append(0)
        out.append(row)
    return out, cov


def attract(game, log):
    if game:
        fmt, width, texels = sheet(game, ATTRACT_TXR, ATTRACT_SHEET)
        if (fmt, width, len(texels)) != (2, 256, 256 * 256):
            raise SystemExit('ADV_TXT.TXR sheet %d is not a 256x256 1555' % ATTRACT_SHEET)
        stock = [texels[(ATTRACT_TOP + y) * 256:(ATTRACT_TOP + y + 1) * 256] for y in range(ATTRACT_ROWS)]
        keys, cov = attract_image(ATTRACT_KEYS, 256)
        white = [[(t >> 10 & 31) / 31.0 if t >> 15 and t != ATTRACT_OUTLINE else 0.0 for t in row] for row in stock]
        inked = [[c if c * 31 >= ATTRACT_INK - 0.5 else 0.0 for c in row] for row in cov]
        log('attract: the model of %s against the stock: %.1f%% of the ink off, %d of %d texels differ in being clear, outline or lettering'
            % (ATTRACT_KEYS, 100 * share(inked, white), sum((s == 0, s == ATTRACT_OUTLINE) != (k == 0, k == ATTRACT_OUTLINE) for srow, krow in zip(stock, keys) for s, k in zip(srow, krow)),
               sum(bool(s) or bool(k) for srow, krow in zip(stock, keys) for s, k in zip(srow, krow))))
    wide = 320
    pad, _cov = attract_image(ATTRACT_PAD, wide)
    lit = [x for x in range(wide) if any(pad[y][x] for y in range(ATTRACT_ROWS))]
    width = lit[-1] - lit[0] + 1
    if ATTRACT_AT[0] + width + 1 > 256:
        raise SystemExit('the attract prompt is %d texels wide, too wide for its sheet' % width)
    if any(pad[0]) or not any(pad[1]):
        raise SystemExit('the attract prompt\'s outline does not start on the second row')
    log('attract: %s, %d by %d' % (ATTRACT_PAD, width, ATTRACT_ROWS))
    return [(ATTRACT_TXR, ATTRACT_ON, ATTRACT_AT[0], ATTRACT_AT[1], width, ATTRACT_ROWS, '', [t for row in pad for t in row[lit[0]:lit[0] + width]])]


