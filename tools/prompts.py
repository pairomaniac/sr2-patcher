def replay(_game, log):
    from PIL import ImageFilter
    parts = []
    reach = 2 * int(round(REPLAY_OUTLINE * SAMPLES)) + 1
    for text, (size, wide, bold), colour in REPLAY_WORDS:
        big = drawn('sans', text, 200, REPLAY_H, 8.0, REPLAY_BASE, size, wide, bold)
        cov = averaged(big, 200, REPLAY_H)
        edge = averaged(big.filter(ImageFilter.MaxFilter(reach)), 200, REPLAY_H)     # the letters and their outline
        cols = [x for x in range(200) if any(c >= 0.1 for c in (edge[y][x] for y in range(REPLAY_H)))]     # the outline included
        parts.append((colour, [row[cols[0]:cols[-1] + 1] for row in cov], [row[cols[0]:cols[-1] + 1] for row in edge]))
    width = sum(len(part[1][0]) for part in parts) + sum(REPLAY_GAPS)
    if width > REPLAY_W - 2:
        raise SystemExit('the replay prompt is %d texels wide, too wide for its plate' % width)
    ink = [[(0, 0.0, 0.0)] * REPLAY_W for _ in range(REPLAY_H)]    # (colour, the letter's coverage, the outline's) a texel
    x = (REPLAY_W - width) // 2
    for i, (colour, cov, edge) in enumerate(parts):
        for y in range(REPLAY_H):
            for dx in range(len(cov[y])):
                old = ink[y][x + dx]
                if cov[y][dx] > old[1]:
                    ink[y][x + dx] = (colour, cov[y][dx], max(edge[y][dx], old[2]))
                else:
                    ink[y][x + dx] = (old[0], old[1], max(edge[y][dx], old[2]))
        x += len(cov[0]) + (REPLAY_GAPS[i] if i < 2 else 0)
    out = []
    for y in range(REPLAY_H):
        for x in range(REPLAY_W):
            colour, c, o = ink[y][x]
            o = min(1.0, o * REPLAY_OUTLINE_GAIN)
            texel = 0xf000
            for shift in (8, 4, 0):
                plate, letter = REPLAY_PLATE >> shift & 15, colour >> shift & 15
                texel |= int(round(plate * (1 - o) + letter * c)) << shift     # black where the outline is and the letter is not
            out.append(texel)
    log('replay: %s, %d wide on the %d plate' % (' '.join(w for w, _s, _c in REPLAY_WORDS), width, REPLAY_W))
    return [(file, REPLAY_SHEET, REPLAY_AT[0], REPLAY_AT[1], REPLAY_W, REPLAY_H, '', out) for file in REPLAY_TXRS]


