#!/usr/bin/env python3
"""Render the pad's prompts and bake them into ../sr2-patcher.py, or check
that they still match.

    python3 tools/prompts.py [GAMEDIR]            # render and write
    python3 tools/prompts.py --check              # verify only, writes nothing
    python3 tools/prompts.py --show DIR GAMEDIR   # also write PNGs to DIR to look at

The game's prompts are lettering in its texture sheets. Each prompt that
names a key gets a twin that names the pad's button, put where a sheet
is free; the patcher writes the texels and asm/padprompts.asm switches
the sprite to them while a pad is held. Each twin is one line of one
font, set and finished as the stock prompt it stands in for. With
GAMEDIR, an installed game, each model is also run on the stock
prompt's own words and compared with the stock texels, which is how the
numbers below were fitted.

  title    TITLE.TXR sheet 5, PRESS ENTER KEY: Times Bold, which Nimbus
           Roman Bold clones, a little wide and bolder across, filled
           with a gradient a row at a time over a black glow.
  attract  ADV_TXT.TXR sheet 0, PRESS ENTER KEY: a humanist bold italic
           set wide, which Open Sans Bold Italic comes closest to, white
           with a dark outline a texel wide.
  records  Record.txr sheet 13, PAGE UP KEY and PAGE DOWN KEY: a narrow
           bold grotesque, 9 px caps, as Liberation Sans Narrow Bold
           (Arial Narrow's metrics), white on clear.

The Device Settings page's two hint lines are made here as well, in the
face of the Options frame's own messages (OPTIONS.TXR sheet 4), which
is that narrow bold grotesque with 11 px caps. So are the masks for two
bitmaps the exe blits: the connection screen's SEARCH button (the lobby
patch) and SEL for TAB on the team room's button (the tabmenu patch),
in Noto Sans Mono, the closest open face to their monospaced 10 px
lettering.

Needs Pillow and the fonts; --check exits 77 with a note without them.
"""
