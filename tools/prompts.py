def packed(blits):
    lines = []
    for file, sheet_, x, y, w, h, variant, texels in blits:
        b64 = base64.b64encode(zlib.compress(struct.pack('<%dH' % len(texels), *texels), 9)).decode('ascii')
        chunks = ["'%s'" % b64[i:i + 96] for i in range(0, len(b64), 96)]
        lines.append("        ('%s', %d, %d, %d, %d, %d, '%s',\n         " % (file, sheet_, x, y, w, h, variant) + '\n         '.join(chunks) + '),\n')
    return lines


def generated(art):
    lines = [BEGIN, '# The pad\'s prompts: key -> ((file, sheet, x, y, width, height, variant, texels), ...),\n',
             '# the file under BINDATA\\\\MISC, the variant \'\' for every release or the language\n',
             '# of the file it goes with, the texels 16-bit and zlib-compressed; see\n',
             '# tools/prompts.py.\n', 'PROMPT_ART = {\n']
    for key, _maker in PROMPTS:
        lines += ["    '%s': (\n" % key] + packed(art[key]) + ['    ),\n']
    lines += ['}\n', '# The Device Settings page\'s hint lines, the same way: each line\'s two\n',
              '# halves, strips for the sheet the patcher appends to OPTIONS.TXR.\n', 'HINT_ART = (\n']
    lines += [line.replace('        (', '    (', 1).replace('\n         ', '\n     ') for line in packed(art[HINTS])]
    lines += [')\n', END]
    return ''.join(lines)


def carried(region):
    """The art the script carries: the generated region run as Python."""
    ns = {}
    exec(region, ns)

    def unpacked(blits):
        out = []
        for file, sheet_, x, y, w, h, variant, b64 in blits:
            raw = zlib.decompress(base64.b64decode(b64))
            out.append((file, sheet_, x, y, w, h, variant, list(struct.unpack('<%dH' % (len(raw) // 2), raw))))
        return out
    out = {key: unpacked(blits) for key, blits in ns['PROMPT_ART'].items()}
    out[HINTS] = unpacked(ns.get('HINT_ART', ()))
    return out


# A font rasterises a little differently from one FreeType or font build
# to the next, so the check does not ask for the baked texels: a render
# is the same art when the blits sit where the baked ones do, at most
# FAR_TOLERANCE of a blit's texels are more than one level of 15 apart
# in any channel, and none is more than FAR levels apart.
FAR_TOLERANCE, FAR = 0.02, 3


def compare(baked, made):
    """What sets two sets of art apart, or '' when nothing does, and
    whether they are the same texel for texel."""
    same = True
    for key in [key for key, _maker in PROMPTS] + [HINTS]:
        a, b = baked.get(key, ()), made[key]
        if [blit[:7] for blit in a] != [blit[:7] for blit in b]:
            return '%s: the blits are not where the baked ones are' % key, False
        for (_f, sheet_, x, y, _w, _h, _v, old), (_f2, _s, _x, _y, _w2, _h2, _v2, new) in zip(a, b):
            apart = [levels(p, q) for p, q in zip(old, new)]
            same = same and not any(apart)
            if max(apart) > FAR or sum(d > 1 for d in apart) > FAR_TOLERANCE * len(apart):
                return '%s, sheet %d at (%d, %d): %d texels more than a level apart, the furthest %d' % (
                    key, sheet_, x, y, sum(d > 1 for d in apart), max(apart)), False
    return '', same


def write_pngs(art, game, folder):
    """Each touched sheet as it will be, over grey, four times the size;
    an appended sheet on its own."""
    from PIL import Image
    os.makedirs(folder, exist_ok=True)
    for key, blits in art.items():
        for (file, index) in dict.fromkeys((b[0], b[1]) for b in blits):
            mine = [b for b in blits if (b[0], b[1]) == (file, index)]
            if not file.lower().endswith('.txr'):           # a bitmap's mask: the coverage over grey
                for _f, _s, x, y, w, h, _v, new in mine:
                    im = Image.new('L', (w, h))
                    im.putdata([255 - (t >> 12) * 13 for t in new])
                    im.resize((w * 4, h * 4), Image.NEAREST).save(os.path.join(folder, '%s-%s.png' % (key, file)))
                continue
            if index < sheet_count(game, file):
                fmt, width, texels = sheet(game, file, index)
            else:
                fmt, width, texels = 8, 256, [0x0fff] * (256 * 256)
            for _f, _s, x, y, w, h, _v, new in mine:
                for dy in range(h):
                    texels[(y + dy) * width + x:(y + dy) * width + x + w] = new[dy * w:(dy + 1) * w]
            im = Image.new('RGB', (width, len(texels) // width))
            if fmt == 8:
                im.putdata([tuple((60 * (15 - (t >> 12)) + (t >> s & 15) * 17 * (t >> 12)) // 15 for s in (8, 4, 0)) for t in texels])
            elif fmt == 2:
                im.putdata([tuple((t >> s & 31) * 8 for s in (10, 5, 0)) if t >> 15 else (60, 60, 60) for t in texels])
            else:
                im.putdata([((t >> 11) * 8, (t >> 5 & 63) * 4, (t & 31) * 8) for t in texels])
            top = max(0, min(b[3] for b in mine) - 40)
            im = im.crop((0, top, width, min(im.height, max(b[3] + b[5] for b in mine) + 8)))
            im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(os.path.join(folder, '%s-%s-%d.png' % (key, file.split('.')[0], index)))


def main(argv):
    args = argv[1:]
    check = '--check' in args
    show = None
    if '--show' in args:
        show = args[args.index('--show') + 1]
        args.remove(show)
    args = [a for a in args if not a.startswith('--')]
    if len(args) > 1 or (show and not args):
        print(__doc__.strip())
        return 2
    game = args[0] if args else None
    with open(TARGET, encoding='utf-8') as fh:
        text = fh.read()
    pattern = re.compile(re.escape(BEGIN) + '.*?' + re.escape(END), re.S)
    if not pattern.search(text):
        raise SystemExit('no prompts region in sr2-patcher.py')
    try:
        art = make(game, print if game or not check else (lambda _line: None))
    except (ImportError, SystemExit) as exc:
        if check and (isinstance(exc, ImportError) or 'not found' in str(exc)):
            print('prompts: skipped (%s)' % exc)
            return SKIPPED
        raise
    if show:
        write_pngs(art, game, show)
    if check:
        why, same = compare(carried(pattern.search(text).group(0)), art)
        if why:
            print('prompts differ: %s; run tools/prompts.py on the machine the art comes from' % why)
            return 1
        print('prompts match' if same else 'note: prompts match within the rasteriser\'s tolerance')
        return 0
    new = generated(art)
    text = pattern.sub(lambda _m: new, text)
    with open(TARGET, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print('wrote %d prompt(s) into sr2-patcher.py' % len(art))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
